/** Duos unlocked by a set of owned boon ids. */
export function availableDuos(ownedIds) {
  const owned = new Set(ownedIds);
  return duo_Boons.filter((d) =>
    d.requires.every((r) => r.any.some((id) => owned.has(id)))
  );
}